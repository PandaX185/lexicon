#!/usr/bin/env bash
# Build the pinned native Bergamot translator used by the `bergamot` build tag.
#
# The source revision and the Ubuntu build image are pinned. Outputs:
#   $BERGAMOT_BUILD/src/translator/libbergamot-translator.a
#   $BERGAMOT_BUILD/libmarian.a
#   $BERGAMOT_BUILD/../env.sh   (CGO flags for the daemon build)
set -euo pipefail

script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
repo_root=$(cd -- "$script_dir/../.." && pwd)

bergamot_ref=${BERGAMOT_REF:-v0.4.5}
bergamot_repo=${BERGAMOT_REPO:-https://github.com/browsermt/bergamot-translator.git}
build_root=${BERGAMOT_BUILD_ROOT:-"$repo_root/build/bergamot"}
source_dir=${BERGAMOT_ROOT:-"$build_root/src"}
build_dir=${BERGAMOT_BUILD:-"$build_root/build-native"}
image=${BERGAMOT_IMAGE:-lexicon-bergamot-build}
# Portable amd64 baseline: intgemm needs SSE4.1+, and x86-64-v2 avoids the
# AVX-512 instructions that `-march=native` can emit on CI runners.
arch=${BERGAMOT_ARCH:-x86-64-v2}
jobs=${JOBS:-$(nproc)}
blas_libs=${BERGAMOT_BLAS_LIBS:--lblas -llapack -lcblas}

for command in docker git; do
    if ! command -v "$command" >/dev/null 2>&1; then
        echo "error: $command is required" >&2
        exit 1
    fi
done

if [[ ! -d "$source_dir/.git" ]]; then
    if [[ -e "$source_dir" ]]; then
        echo "error: $source_dir exists but is not a git checkout" >&2
        exit 1
    fi
    mkdir -p "$(dirname -- "$source_dir")"
    echo "cloning bergamot-translator $bergamot_ref into $source_dir"
    git clone --depth 1 --branch "$bergamot_ref" \
        --recurse-submodules --shallow-submodules \
        "$bergamot_repo" "$source_dir"
else
    current=$(git -C "$source_dir" describe --tags --always --dirty 2>/dev/null || printf unknown)
    if [[ "$current" != "$bergamot_ref" ]]; then
        echo "warning: $source_dir is at $current, expected $bergamot_ref" >&2
        echo "         remove the directory to re-clone the pinned revision" >&2
    fi
    git -C "$source_dir" submodule update --init --recursive --depth 1
fi

echo "building $image"
docker build -t "$image" -f "$script_dir/Dockerfile" "$script_dir"

mkdir -p "$build_dir"
echo "configuring bergamot in $build_dir (arch: $arch)"
docker run --rm \
    --user "$(id -u):$(id -g)" \
    -e HOME=/tmp \
    -v "$source_dir:$source_dir" \
    -v "$build_dir:$build_dir" \
    -v "$script_dir:$script_dir:ro" \
    -w "$build_dir" \
    "$image" \
    bash -lc "cmake -S '$source_dir' -B '$build_dir' \
        -DCMAKE_BUILD_TYPE=Release \
        -DCOMPILE_TESTS=OFF \
        -DCOMPILE_UNIT_TESTS=OFF \
        -DCOMPILE_CUDA=OFF \
        -DCOMPILE_WASM=OFF \
        -DGIT_SUBMODULE=OFF \
        -DBUILD_ARCH='$arch' \
        -DCMAKE_PROJECT_TOP_LEVEL_INCLUDES='$script_dir/cstdint.cmake'"

echo "building bergamot ($jobs jobs)"
docker run --rm \
    --user "$(id -u):$(id -g)" \
    -e HOME=/tmp \
    -v "$source_dir:$source_dir" \
    -v "$build_dir:$build_dir" \
    -v "$script_dir:$script_dir:ro" \
    -w "$build_dir" \
    "$image" \
    cmake --build "$build_dir" --parallel "$jobs"

for artifact in \
    "$build_dir/src/translator/libbergamot-translator.a" \
    "$build_dir/libmarian.a" \
    "$build_dir/app/bergamot"; do
    if [[ ! -f "$artifact" ]]; then
        echo "error: expected build artifact is missing: $artifact" >&2
        exit 1
    fi
done

env_file="$build_root/env.sh"
cat > "$env_file" <<EOF
# Generated by tools/bergamot/build.sh. Source before building the daemon:
#   source build/bergamot/env.sh
#   just daemon_go_tags=bergamot core
export BERGAMOT_ROOT="$source_dir"
export BERGAMOT_BUILD="$build_dir"
export CGO_ENABLED=1
export CGO_CXXFLAGS="-std=c++17 -O2 -include cstdint \\
-I$source_dir \\
-I$source_dir/src \\
-I$source_dir/3rd_party/marian-dev/src \\
-I$source_dir/3rd_party/marian-dev/src/3rd_party \\
-I$source_dir/3rd_party/marian-dev/src/3rd_party/sentencepiece/src \\
-I$source_dir/3rd_party/marian-dev/src/3rd_party/intgemm \\
-I$source_dir/3rd_party/ssplit-cpp/src \\
-I$source_dir/3rd_party/ssplit-cpp/src/ssplit"
export CGO_LDFLAGS="-L$build_dir/src/translator \\
-L$build_dir \\
-L$build_dir/3rd_party/marian-dev/src/3rd_party/sentencepiece/src \\
-L$build_dir/3rd_party/marian-dev/src/3rd_party/intgemm \\
-lbergamot-translator -lmarian -lsentencepiece_train -lsentencepiece \\
-lintgemm -lssplit $blas_libs -lpcre2-8 -ldl -lpthread -lstdc++ -lm"
EOF

echo
echo "built bergamot $bergamot_ref"
echo "  source: $source_dir"
echo "  build:  $build_dir"
echo "  cgo:    $env_file"
echo
echo "next:"
echo "  source $env_file"
echo "  just daemon_go_tags=bergamot core"
echo "  just bergamot-test /path/to/model-pack"
